def test_experiment_index_covers_all_records(generated: dict[str, str]) -> None:
    records = load_experiment_records()
    assert len(records) == 21, f"expected 21 experiment records, got {len(records)}"
    doc = generated["experiment_index.md"]
    for record in records:
        assert record["id"] in doc, (
            f"experiment record {record['id']} missing from experiment_index.md"
        )


def test_experiment_index_grouped_by_record_kind(generated: dict[str, str]) -> None:
    records = load_experiment_records()
    executable = [r for r in records if r["record_kind"] == "executable_definition"]
    historical = [r for r in records if r["record_kind"] == "historical_artifact"]
    assert len(executable) == 13 and len(historical) == 8
    doc = generated["experiment_index.md"]
    executable_header = re.search(
        rf"^## .*[Ee]xecutable.*\({len(executable)}\)", doc, re.MULTILINE
    )
    historical_header = re.search(
        rf"^## .*[Hh]istorical.*\({len(historical)}\)", doc, re.MULTILINE
    )
    assert executable_header, "executable definitions group header with count missing"
    assert historical_header, "historical artifacts group header with count missing"
    assert executable_header.start() < historical_header.start(), (
        "executable definitions must be grouped before historical artifacts"
    )


def test_executable_records_have_config_and_entrypoint_links(
    generated: dict[str, str],
) -> None:
    doc = generated["experiment_index.md"]
    for record in load_experiment_records():
        if record["record_kind"] != "executable_definition":
            continue
        assert record["runnable"] in doc, (
            f"runnable mode {record['runnable']} for {record['id']} missing"
        )
        assert record["handler"] in doc, f"handler for {record['id']} missing"
        assert record["evaluation_scope"]["kind"] in doc, (
            f"scope kind for {record['id']} missing"
        )
        assert record["config_path"] in doc, f"config path for {record['id']} missing"
        assert record["legacy_entrypoint"] in doc, (
            f"entrypoint for {record['id']} missing"
        )


def test_historical_records_have_evidence_pointers(generated: dict[str, str]) -> None:
    doc = generated["experiment_index.md"]
    for record in load_experiment_records():
        if record["record_kind"] != "historical_artifact":
            continue
        assert record["evidence_kind"] in doc, (
            f"evidence kind for {record['id']} missing"
        )
        assert record["source_evidence_pointer"] in doc, (
            f"evidence pointer for {record['id']} missing"
        )


# ---------------------------------------------------------------------------
# artifact_index.md: reviewed manifests only; explicit empty state now
# ---------------------------------------------------------------------------


def test_artifact_index_empty_state(generated: dict[str, str]) -> None:
    manifests = reviewed_manifest_paths()
    doc = generated["artifact_index.md"]
    if not manifests:
        assert "No reviewed artifact manifests exist yet." in doc, (
            "artifact_index.md must state the explicit empty state while "
            "configs/registry/artifacts/ has no manifests"
        )
    else:
        for path in manifests:
            payload = json.loads(path.read_text(encoding="utf-8"))
            assert payload["manifest_id"] in doc
            assert payload["experiment_id"] in doc


def test_artifact_index_has_no_fabricated_metrics(generated: dict[str, str]) -> None:
    if reviewed_manifest_paths():
        pytest.skip("reviewed manifests exist; empty-state metric check not applicable")
    doc = generated["artifact_index.md"]
    # With zero reviewed manifests the index must not show any metric values.
    assert not re.search(r"\bap50\b|\bap75\b|\bmetrics_summary\b", doc, re.IGNORECASE), (
        "artifact_index.md must not fabricate metric rows without reviewed manifests"
    )
