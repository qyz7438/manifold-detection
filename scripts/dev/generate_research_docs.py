"""Deterministic generator for the tracked research docs (refactor Task 8).

Regenerates the four tracked files under ``docs/research/``:

* ``README.md``           index of the research docs plus maintained prose
                          explaining how the registries govern status;
* ``current_status.md``   every research line with status, claim ceiling, and
                          decision document — status comes ONLY from
                          ``spectral_detection_posttrain/configs/registry/
                          research_lines.json``;
* ``experiment_index.md`` all experiment records grouped by record kind —
                          records come ONLY from ``experiments.json``;
* ``artifact_index.md``   metric rows from reviewed artifact manifests under
                          ``configs/registry/artifacts/`` ONLY. While the
                          directory holds no reviewed manifests the index
                          renders an explicit empty state instead of rows.

Determinism rules (enforced by
``tests/experiments/test_generated_research_docs.py``):

* sorted by stable IDs (research line id, experiment record id, manifest id);
* UTF-8, LF line endings, exactly one trailing newline;
* no timestamps — dates live in ``docs/research/refactor_ledger.md``;
* relative links only: link text shows the repo-relative path, the link
  target is relative to the generated file's own directory so it resolves
  both on disk and on the forge;
* every file starts with a visible generated-file header listing the
  generation inputs (registry file names plus their sha256 digests) so any
  drift is explainable.

CLI:

* ``python scripts/dev/generate_research_docs.py --write``  regenerate the
  four tracked files;
* ``python scripts/dev/generate_research_docs.py --check``  regenerate in
  memory and exit 1 on drift;
* ``--out-dir <dir>`` writes/compares against another directory (used by
  tests).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
REGISTRY_DIR_REPO = "spectral_detection_posttrain/configs/registry"
RESEARCH_LINES_REPO = f"{REGISTRY_DIR_REPO}/research_lines.json"
EXPERIMENTS_REPO = f"{REGISTRY_DIR_REPO}/experiments.json"
ARTIFACTS_DIR_REPO = f"{REGISTRY_DIR_REPO}/artifacts"
DOCS_DIR_REPO = "docs/research"
DEFAULT_DOCS_DIR = ROOT / "docs" / "research"
GENERATOR_REPO_PATH = "scripts/dev/generate_research_docs.py"
ARTIFACTS_MODULE_REPO = "spectral_detection_posttrain/experiments/artifacts.py"

GENERATED_FILE_NAMES = ("README.md", "current_status.md", "experiment_index.md", "artifact_index.md")

GENERATED_MARKER = (
    f"<!-- GENERATED by {GENERATOR_REPO_PATH} — do not edit by hand -->"
)

NO_REVIEWED_MANIFESTS_SENTENCE = "No reviewed artifact manifests exist yet."

_ACTIVE_STATUSES = ("active", "queued")
_MAIN_LINE_STATUSES = ("frozen", "blocked")

# Light structural validation for reviewed manifests rendered into
# artifact_index.md; the strict contract lives in
# ``spectral_detection_posttrain/experiments/artifacts.py`` and its tests.
_MANIFEST_REQUIRED_KEYS = (
    "manifest_kind",
    "manifest_id",
    "experiment_id",
    "completion",
    "evaluation_scope",
    "metrics_summary",
    "source_evidence_pointer",
)


# ---------------------------------------------------------------------------
# Inputs
# ---------------------------------------------------------------------------


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _registry_dir(root: Path) -> Path:
    return root / "spectral_detection_posttrain" / "configs" / "registry"


def _load_research_lines(root: Path) -> list[dict]:
    payload = _load_json(_registry_dir(root) / "research_lines.json")
    return sorted(payload["lines"], key=lambda line: line["id"])


def _load_experiment_records(root: Path) -> list[dict]:
    payload = _load_json(_registry_dir(root) / "experiments.json")
    return sorted(payload["records"], key=lambda record: record["id"])


def _load_reviewed_manifests(root: Path) -> list[tuple[str, dict]]:
    """Return ``(repo_path, payload)`` pairs for reviewed manifests, sorted by id.

    A missing or empty artifacts directory is the expected initial state and
    yields an empty list. Manifest files that fail light structural
    validation raise: generation must fail loudly rather than silently skip
    or fabricate rows.
    """
    artifacts_dir = _registry_dir(root) / "artifacts"
    if not artifacts_dir.is_dir():
        return []
    manifests = []
    for path in sorted(artifacts_dir.glob("*.json")):
        payload = _load_json(path)
        if not isinstance(payload, dict):
            raise ValueError(f"artifact manifest must be a JSON object: {path}")
        missing = [key for key in _MANIFEST_REQUIRED_KEYS if key not in payload]
        if missing:
            raise ValueError(f"artifact manifest {path} is missing field(s): {missing}")
        if payload["manifest_kind"] != "reviewed":
            raise ValueError(
                f"only reviewed manifests may be indexed: {path} has "
                f"manifest_kind={payload['manifest_kind']!r}"
            )
        repo_path = f"{ARTIFACTS_DIR_REPO}/{path.name}"
        manifests.append((repo_path, payload))
    manifests.sort(key=lambda item: item[1]["manifest_id"])
    return manifests


def _input_lines(root: Path) -> list[str]:
    """Generation-input descriptors with sha256 digests for the header block."""
    registry = _registry_dir(root)
    lines = [
        f"{RESEARCH_LINES_REPO} sha256={_sha256_file(registry / 'research_lines.json')}",
        f"{EXPERIMENTS_REPO} sha256={_sha256_file(registry / 'experiments.json')}",
    ]
    manifests = _load_reviewed_manifests(root)
    if manifests:
        for repo_path, _payload in manifests:
            lines.append(f"{repo_path} sha256={_sha256_file(root / repo_path)}")
    else:
        lines.append(f"{ARTIFACTS_DIR_REPO}/ (no reviewed manifests)")
    return lines


def _header(root: Path) -> list[str]:
    lines = [GENERATED_MARKER, "<!-- generation inputs:"]
    lines.extend(f"     {entry}" for entry in _input_lines(root))
    lines.append("-->")
    return lines


# ---------------------------------------------------------------------------
# Rendering helpers
# ---------------------------------------------------------------------------


def _rel_link(doc_name: str, repo_path: str, root: Path) -> str:
    """Markdown link whose text is the repo-relative path and whose target is
    relative to the generated file's own directory (``docs/research/``)."""
    from_dir = (root / DOCS_DIR_REPO).resolve()
    target = os.path.relpath((root / repo_path).resolve(), start=from_dir)
    return f"[{repo_path}]({target.replace(os.sep, '/')})"


def _escape_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    return f"`{text}`"


def _format_scope(scope: dict) -> str:
    kind = str(scope.get("kind"))
    details = []
    if scope.get("image_count") is not None:
        details.append(f"{scope['image_count']} images")
    limits = []
    if scope.get("limit_train") is not None:
        limits.append(f"train {scope['limit_train']}")
    if scope.get("limit_val") is not None:
        limits.append(f"val {scope['limit_val']}")
    if limits:
        details.append(" / ".join(limits))
    if details:
        return f"{kind} ({'; '.join(details)})"
    return kind


def _finish(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


